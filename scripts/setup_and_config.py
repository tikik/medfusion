def bootstrap_confidence_interval(preds_a, preds_b, labels, metric='accuracy', n_bootstrap=1000, alpha=0.05):
    """
    Calculate bootstrap confidence intervals for metric differences

    Args:
        preds_a: Predictions from model A
        preds_b: Predictions from model B
        labels: True labels
        metric: 'accuracy' or 'f1_macro'
        n_bootstrap: Number of bootstrap samples
        alpha: Significance level

    Returns:
        CI_lower, CI_upper, p_value
    """
    n_samples = len(labels)
    differences = []

    # Define metric function
    if metric == 'accuracy':
        def calculate_metric(preds, true):
            return np.mean(preds == true)
    else:  # f1_macro
        from sklearn.metrics import f1_score
        def calculate_metric(preds, true):
            return f1_score(true, preds, average='macro', zero_division=0)

    # Calculate observed difference
    metric_a = calculate_metric(preds_a, labels)
    metric_b = calculate_metric(preds_b, labels)
    observed_diff = metric_a - metric_b

    # Bootstrap sampling
    for _ in range(n_bootstrap):
        # Resample with replacement
        indices = np.random.choice(n_samples, n_samples, replace=True)
        sample_preds_a = [preds_a[i] for i in indices]
        sample_preds_b = [preds_b[i] for i in indices]
        sample_labels = [labels[i] for i in indices]

        # Calculate metric difference
        diff = (calculate_metric(sample_preds_a, sample_labels) -
                calculate_metric(sample_preds_b, sample_labels))
        differences.append(diff)

    # Calculate confidence interval
    differences = np.array(differences)
    ci_lower = np.percentile(differences, alpha/2 * 100)
    ci_upper = np.percentile(differences, (1 - alpha/2) * 100)

    # Calculate p-value (two-tailed)
    p_value = 2 * min(
        np.mean(differences <= 0) if observed_diff > 0 else np.mean(differences >= 0),
        np.mean(differences >= 0) if observed_diff > 0 else np.mean(differences <= 0)
    )

    return {
        'observed_difference': float(observed_diff),
        'ci_lower': float(ci_lower),
        'ci_upper': float(ci_upper),
        'p_value': float(p_value),
        'significant': str(ci_lower > 0 or ci_upper < 0) # Converted boolean to string
    }

