class RandomBaseline:
    """Random guessing baseline"""
    def __init__(self, num_classes=5, seed=42):
        self.num_classes = num_classes
        self.seed = seed
        np.random.seed(seed)

    def predict(self, n_samples):
        return np.random.randint(0, self.num_classes, n_samples)

    def predict_proba(self, n_samples):
        """Random probabilities"""
        probs = np.random.rand(n_samples, self.num_classes)
        return probs / probs.sum(axis=1, keepdims=True)

class MajorityBaseline:
    """Always predict the majority class"""
    def __init__(self, majority_class):
        self.majority_class = majority_class

    def predict(self, n_samples):
        return np.full(n_samples, self.majority_class)

    def predict_proba(self, n_samples):
        probs = np.zeros((n_samples, self.majority_class + 1))
        probs[:, self.majority_class] = 1.0
        return probs

class SimpleCNNBaseline(nn.Module):
    """Simple CNN for image-only baseline (what you likely used)"""
    def __init__(self, num_classes=5, image_size=224):
        super().__init__()

        # Calculate flattened size
        feature_size = image_size // 4  # After 2 pooling layers

        self.features = nn.Sequential(
            # Layer 1
            nn.Conv2d(3, 16, kernel_size=3, padding=1),
            nn.ReLU(),
            nn.MaxPool2d(2),  # 224 -> 112

            # Layer 2
            nn.Conv2d(16, 32, kernel_size=3, padding=1),
            nn.ReLU(),
            nn.MaxPool2d(2),  # 112 -> 56

            # Layer 3
            nn.Conv2d(32, 64, kernel_size=3, padding=1),
            nn.ReLU(),
            nn.MaxPool2d(2),  # 56 -> 28
        )

        self.classifier = nn.Sequential(
            nn.Flatten(),
            nn.Linear(64 * feature_size * feature_size // 4, 128),
            nn.ReLU(),
            nn.Dropout(0.5),
            nn.Linear(128, num_classes)
        )

    def forward(self, x):
        x = self.features(x)
        x = self.classifier(x)
        return x

