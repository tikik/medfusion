class MedFusion(nn.Module):
    """
    MedFusion: Multimodal VQA model

    Truth: We're using Bio_ClinicalBERT for text and a Simple CNN for images
    NOT using BiomedCLIP (despite earlier claims in architecture diagram)
    """

    def __init__(self, num_classes=5, dropout=0.3, use_simple_cnn=True):
        super().__init__()

        print("Initializing MedFusion...")
        print("  Text encoder: Bio_ClinicalBERT")
        print("  Image encoder: Simple CNN (not BiomedCLIP)")

        # ============================================
        # TEXT ENCODER: Bio_ClinicalBERT
        # ============================================
        try:
            self.text_encoder = AutoModel.from_pretrained(
                "emilyalsentzer/Bio_ClinicalBERT"
            )
            self.text_proj = nn.Linear(768, 256)
            print("  ✓ Loaded Bio_ClinicalBERT")
        except:
            print("  ✗ Could not load Bio_ClinicalBERT, using placeholder")
            self.text_encoder = None
            self.text_proj = nn.Linear(768, 256)

        # ============================================
        # IMAGE ENCODER: Simple CNN (TRUTH)
        # ============================================
        if use_simple_cnn:
            # This is what you actually used based on 20% baseline
            self.image_encoder = nn.Sequential(
                # Block 1
                nn.Conv2d(3, 16, kernel_size=3, padding=1),
                nn.BatchNorm2d(16),
                nn.ReLU(),
                nn.MaxPool2d(2),  # 224 -> 112

                # Block 2
                nn.Conv2d(16, 32, kernel_size=3, padding=1),
                nn.BatchNorm2d(32),
                nn.ReLU(),
                nn.MaxPool2d(2),  # 112 -> 56

                # Block 3
                nn.Conv2d(32, 64, kernel_size=3, padding=1),
                nn.BatchNorm2d(64),
                nn.ReLU(),
                nn.MaxPool2d(2),  # 56 -> 28

                # Global pooling
                nn.AdaptiveAvgPool2d((1, 1)),
                nn.Flatten(),
                nn.Linear(64, 256)
            )
            print("  ✓ Using Simple CNN image encoder")
        else:
            # Placeholder for actual BiomedCLIP (not implemented)
            self.image_encoder = None
            print("  ✗ BiomedCLIP not implemented")

        # ============================================
        # FUSION AND CLASSIFICATION
        # ============================================
        self.fusion_dropout = nn.Dropout(dropout)
        self.fusion_layer = nn.Linear(512, 256)  # 256 + 256 = 512
        self.classifier = nn.Linear(256, num_classes)

        # Tokenizer
        try:
            self.tokenizer = AutoTokenizer.from_pretrained(
                "emilyalsentzer/Bio_ClinicalBERT"
            )
        except:
            self.tokenizer = None

        # Freeze text encoder initially
        if self.text_encoder:
            for param in self.text_encoder.parameters():
                param.requires_grad = False

        print(f"  Total parameters: {sum(p.numel() for p in self.parameters()):,}")
        print(f"  Trainable parameters: {sum(p.numel() for p in self.parameters() if p.requires_grad):,}")

    def forward(self, input_ids, attention_mask, pixel_values):
        """
        Forward pass

        Args:
            input_ids: Tokenized text [batch, seq_len]
            attention_mask: Attention mask [batch, seq_len]
            pixel_values: Images [batch, 3, 224, 224]
        """
        batch_size = pixel_values.shape[0]

        # ============================================
        # TEXT ENCODING
        # ============================================
        if self.text_encoder is not None:
            text_outputs = self.text_encoder(
                input_ids=input_ids,
                attention_mask=attention_mask
            )
            # Use [CLS] token
            text_features = text_outputs.last_hidden_state[:, 0, :]
        else:
            # Placeholder if text encoder failed to load
            text_features = torch.randn(batch_size, 768, device=pixel_values.device)

        text_features = F.relu(self.text_proj(text_features))

        # ============================================
        # IMAGE ENCODING
        # ============================================
        if self.image_encoder is not None:
            image_features = self.image_encoder(pixel_values)
        else:
            # Placeholder
            image_features = torch.randn(batch_size, 256, device=pixel_values.device)

        # ============================================
        # LATE FUSION
        # ============================================
        fused_features = torch.cat([text_features, image_features], dim=1)
        fused_features = self.fusion_dropout(fused_features)

        # ============================================
        # CLASSIFICATION
        # ============================================
        fused_features = F.relu(self.fusion_layer(fused_features))
        logits = self.classifier(fused_features)

        return logits

    def get_tokenizer(self):
        """Get tokenizer for text preprocessing"""
        return self.tokenizer

