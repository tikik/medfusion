def run_training_pipeline(splits_path='data/splits', output_dir='checkpoints', epochs=10):
    """
    Complete training pipeline that connects all components
    """
    print("="*60)
    print("MEDFUSION TRAINING PIPELINE")
    print("="*60)

    try:
        # 1. Load data splits
        from datasets import DatasetDict
        splits = DatasetDict.load_from_disk(splits_path)
        print(f"✓ Loaded data splits: {len(splits['train'])} train, "
              f"{len(splits['val'])} val, {len(splits['test'])} test")

        # 2. Load label mappings
        with open('data/label_mappings.json', 'r') as f:
            label_mappings = json.load(f)
            id2label = {int(k): v for k, v in label_mappings['id2label'].items()}

        # 3. Create dataset (removed problematic import, classes are now defined directly)
        tokenizer = AutoTokenizer.from_pretrained("emilyalsentzer/Bio_ClinicalBERT")

        train_dataset = MedFusionDataset(splits['train'], tokenizer)
        val_dataset = MedFusionDataset(splits['val'], tokenizer)
        test_dataset = MedFusionDataset(splits['test'], tokenizer)

        print("✓ Created datasets")

        # 4. Create dataloaders
        train_loader = DataLoader(train_dataset, batch_size=4, shuffle=True, num_workers=0)
        val_loader = DataLoader(val_dataset, batch_size=4, shuffle=False, num_workers=0)
        test_loader = DataLoader(test_dataset, batch_size=4, shuffle=False, num_workers=0)

        # 5. Initialize model
        device = torch.device("cuda" if torch.cuda.is_available() else "cpu")
        model = MedFusion(num_classes=len(id2label))

        # 6. Calculate class weights
        trainer = MedFusionTrainer(model, device)
        train_labels = splits['train']['label']
        class_weights = trainer.calculate_class_weights(train_labels)

        # Reinitialize trainer with class weights
        trainer = MedFusionTrainer(model, device, class_weights=class_weights)

        print(f"✓ Initialized model on {device}")
        print(f"✓ Using class weights: {class_weights}")

        # 7. Training loop
        best_val_acc = 0

        for epoch in range(1, epochs + 1):
            print(f"\nEpoch {epoch}/{epochs}")

            # Train
            train_loss, train_acc = trainer.train_epoch(train_loader, epoch)

            # Validate
            val_loss, val_acc, _, _, _ = trainer.evaluate(val_loader, 'val')

            print(f"  Train Loss: {train_loss:.4f}, Train Acc: {train_acc:.3f}")
            print(f"  Val Loss: {val_loss:.4f}, Val Acc: {val_acc:.3f}")

            # Save best model
            if val_acc > best_val_acc:
                best_val_acc = val_acc
                trainer.save_checkpoint(output_dir, epoch, is_best=True)
                print(f"  ✓ New best model (Val Acc: {val_acc:.3f})")

            # Save checkpoint every 2 epochs
            if epoch % 2 == 0:
                trainer.save_checkpoint(output_dir, epoch)

        # 8. Final test evaluation
        print("\n" + "-"*60)
        print("FINAL TEST EVALUATION")
        print("-"*60)

        test_loss, test_acc, test_preds_list, test_labels_list, test_probs = trainer.evaluate(test_loader, 'test')

        # Convert lists to NumPy arrays for metric calculation
        test_labels_np = np.array(test_labels_list)
        test_preds_np = np.array(test_preds_list)

        # Calculate metrics
        metrics = calculate_metrics(test_labels_np, test_preds_np, test_probs, id2label)

        print(f"\nTest Results:")
        print(f"  Accuracy: {test_acc:.3f}")
        print(f"  F1-Macro: {metrics['f1_macro']:.3f}")
        print(f"  Precision: {metrics['precision_macro']:.3f}")
        print(f"  Recall: {metrics['recall_macro']:.3f}")

        # 9. Plot confusion matrix
        class_names = [id2label[i] for i in range(len(id2label))]
        cm = confusion_matrix(test_labels_np, test_preds_np)
        plot_confusion_matrix(cm, class_names,
                             title='MedFusion Confusion Matrix (Test Set)',
                             save_path='results/medfusion_confusion.png')

        # 10. Plot training history
        plot_training_history(trainer, save_path='results/training_history.png')

        # 11. Save results
        results = {
            'medfusion': {
                'accuracy': float(test_acc),
                'f1_macro': float(metrics['f1_macro']),
                'precision_macro': float(metrics['precision_macro']),
                'recall_macro': float(metrics['recall_macro']),
                'auc_ovr': metrics['auc_ovr'],
                'auc_ovo': metrics['auc_ovo'],
                'predictions': test_preds_np.tolist(),
                'true_labels': test_labels_np.tolist()
            }
        }

        os.makedirs('results', exist_ok=True)
        with open('results/medfusion_results.json', 'w') as f:
            json.dump(results, f, indent=2)

        print(f"\n✓ Results saved to 'results/medfusion_results.json'")
    except Exception as e:
        print(f"An error occurred during training pipeline: {e}")

