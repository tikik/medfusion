class MedFusionTrainer:
    """Trainer for MedFusion with class weighting"""

    def __init__(self, model, device, class_weights=None, learning_rate=2e-5):
        self.model = model
        self.device = device
        self.model.to(device)

        # Weighted loss for class imbalance
        if class_weights is not None:
            class_weights = torch.tensor(class_weights, device=device, dtype=torch.float32)
            self.criterion = nn.CrossEntropyLoss(weight=class_weights)
            print(f"Using weighted loss with weights: {class_weights.cpu().numpy()}")
        else:
            self.criterion = nn.CrossEntropyLoss()

        # Optimizer - only train unfrozen parameters
        trainable_params = [p for p in model.parameters() if p.requires_grad]
        self.optimizer = torch.optim.AdamW(
            trainable_params,
            lr=learning_rate,
            weight_decay=0.01
        )

        # Learning rate scheduler
        self.scheduler = torch.optim.lr_scheduler.CosineAnnealingLR(
            self.optimizer, T_max=20
        )

        # Track history
        self.history = {
            'train_loss': [], 'train_acc': [],
            'val_loss': [], 'val_acc': [],
            'test_loss': None, 'test_acc': None
        }

    def calculate_class_weights(self, train_labels):
        """Calculate weights inversely proportional to class frequency"""
        from collections import Counter
        counts = Counter(train_labels)
        n_classes = len(counts)
        total = sum(counts.values())

        weights = []
        for class_id in range(n_classes):
            if class_id in counts:
                weight = total / (n_classes * counts[class_id])
            else:
                weight = 1.0  # Default if class missing
            weights.append(weight)

        # Normalize
        weights = torch.tensor(weights, dtype=torch.float32)
        weights = weights / weights.sum() * n_classes

        return weights.tolist()

    def train_epoch(self, train_loader, epoch):
        """Train for one epoch"""
        self.model.train()
        total_loss = 0
        correct = 0
        total = 0

        pbar = tqdm(train_loader, desc=f"Epoch {epoch} Training")
        for batch_idx, batch in enumerate(pbar):
            # Move to device
            batch = {k: v.to(self.device) for k, v in batch.items()}
            labels = batch['labels']

            # Forward pass
            self.optimizer.zero_grad()
            logits = self.model(
                input_ids=batch['input_ids'],
                attention_mask=batch['attention_mask'],
                pixel_values=batch['pixel_values']
            )

            # Calculate loss
            loss = self.criterion(logits, labels)

            # Backward pass
            loss.backward()

            # Gradient clipping
            torch.nn.utils.clip_grad_norm_(self.model.parameters(), 1.0)

            # Optimizer step
            self.optimizer.step()

            # Statistics
            total_loss += loss.item()
            preds = torch.argmax(logits, dim=1)
            correct += (preds == labels).sum().item()
            total += labels.size(0)

            # Update progress bar
            pbar.set_postfix({
                'loss': f'{loss.item():.4f}',
                'acc': f'{correct/total:.3f}'
            })

        avg_loss = total_loss / len(train_loader)
        accuracy = correct / total

        self.history['train_loss'].append(avg_loss)
        self.history['train_acc'].append(accuracy)

        return avg_loss, accuracy

    def evaluate(self, data_loader, mode='val'):
        """Evaluate model"""
        self.model.eval()
        total_loss = 0
        correct = 0
        total = 0

        all_preds = []
        all_labels = []
        all_probs = []

        with torch.no_grad():
            pbar = tqdm(data_loader, desc=f"{mode.capitalize()} Evaluation")
            for batch in pbar:
                batch = {k: v.to(self.device) for k, v in batch.items()}
                labels = batch['labels']

                # Forward pass
                logits = self.model(
                    input_ids=batch['input_ids'],
                    attention_mask=batch['attention_mask'],
                    pixel_values=batch['pixel_values']
                )

                # Calculate loss
                loss = self.criterion(logits, labels)
                total_loss += loss.item()

                # Get predictions and probabilities
                probs = torch.softmax(logits, dim=1)
                preds = torch.argmax(logits, dim=1)

                correct += (preds == labels).sum().item()
                total += labels.size(0)

                # Store for metrics
                all_preds.extend(preds.cpu().numpy())
                all_labels.extend(labels.cpu().numpy())
                all_probs.extend(probs.cpu().numpy())

                pbar.set_postfix({
                    'loss': f'{loss.item():.4f}',
                    'acc': f'{correct/total:.3f}'
                })

        avg_loss = total_loss / len(data_loader)
        accuracy = correct / total

        if mode == 'val':
            self.history['val_loss'].append(avg_loss)
            self.history['val_acc'].append(accuracy)
        elif mode == 'test':
            self.history['test_loss'] = avg_loss
            self.history['test_acc'] = accuracy

        return avg_loss, accuracy, all_preds, all_labels, all_probs

    def save_checkpoint(self, path, epoch, is_best=False):
        """Save model checkpoint"""
        checkpoint = {
            'epoch': epoch,
            'model_state_dict': self.model.state_dict(),
            'optimizer_state_dict': self.optimizer.state_dict(),
            'scheduler_state_dict': self.scheduler.state_dict(),
            'history': self.history
        }

        # Ensure the target directory for checkpoints exists
        os.makedirs(path, exist_ok=True) # Modified line

        if is_best:
            save_path = os.path.join(path, 'best_model.pth')
        else:
            save_path = os.path.join(path, f'checkpoint_epoch_{epoch}.pth')

        torch.save(checkpoint, save_path)
        print(f"  ✓ Saved checkpoint to {save_path}")

    def load_checkpoint(self, path):
        """Load model checkpoint"""
        checkpoint = torch.load(path, map_location=self.device)
        self.model.load_state_dict(checkpoint['model_state_dict'])
        self.optimizer.load_state_dict(checkpoint['optimizer_state_dict'])
        self.scheduler.load_state_dict(checkpoint['scheduler_state_dict'])
        self.history = checkpoint['history']
        return checkpoint['epoch']

