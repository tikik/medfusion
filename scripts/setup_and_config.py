def calculate_metrics(true_labels, predictions, probabilities, id2label):
    """Calculate comprehensive metrics"""
    from sklearn.metrics import roc_auc_score, precision_score, recall_score
    from sklearn.preprocessing import label_binarize

    n_classes = len(id2label)

    # Convert true_labels and predictions to numpy arrays if they aren't already
    true_labels = np.asarray(true_labels)
    predictions = np.asarray(predictions)

    # Basic metrics
    accuracy = accuracy_score(true_labels, predictions)
    f1_macro = f1_score(true_labels, predictions, average='macro', zero_division=0)
    precision_macro = precision_score(true_labels, predictions, average='macro', zero_division=0)
    recall_macro = recall_score(true_labels, predictions, average='macro', zero_division=0)

    # AUC
    auc_ovr = auc_ovo = np.nan
    if n_classes > 1 and probabilities is not None:
        try:
            true_binary = label_binarize(true_labels, classes=range(n_classes))
            auc_ovr = roc_auc_score(true_binary, probabilities, average='macro', multi_class='ovr')
            auc_ovo = roc_auc_score(true_binary, probabilities, average='macro', multi_class='ovo')
        except:
            pass

    # Confusion matrix
    cm = confusion_matrix(true_labels, predictions)

    # Per-class metrics
    per_class = {}
    for class_id in range(n_classes):
        class_mask = (true_labels == class_id)
        if class_mask.any():
            class_acc = (predictions[class_mask] == class_id).mean()
            per_class[class_id] = {
                'accuracy': float(class_acc),
                'label': id2label[class_id]
            }

    return {
        'accuracy': float(accuracy),
        'f1_macro': float(f1_macro),
        'precision_macro': float(precision_macro),
        'recall_macro': float(recall_macro),
        'auc_ovr': float(auc_ovr) if not np.isnan(auc_ovr) else None,
        'auc_ovo': float(auc_ovo) if not np.isnan(auc_ovo) else None,
        'confusion_matrix': cm.tolist(),
        'per_class': per_class
    }

