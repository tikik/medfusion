def load_mmmed_dataset():
    """Load and explore MMMED dataset"""
    print("Loading MMMED dataset...")
    dataset = load_dataset("praiselab-picuslab/MMMED")

    # Use English split
    if 'English' in dataset:
        ds = dataset['English']
        print(f"✓ Loaded English split: {len(ds)} samples")
