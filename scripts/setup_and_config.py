def prepare_labels(dataset, label_column='Correct Letter'):
    """Convert string labels to numeric IDs"""
    print(f"\nPreparing labels from '{label_column}'...")

    # Get unique labels and create mappings
    unique_labels = sorted(list(set(dataset[label_column])))
    label2id = {label: idx for idx, label in enumerate(unique_labels)}
    id2label = {idx: label for label, idx in label2id.items()}

    print(f"Found {len(unique_labels)} classes: {unique_labels}")
    print(f"Label mapping: {label2id}")

    # Apply mapping
    def map_label(example):
        example['label'] = label2id[example[label_column]]
        return example

    labeled_ds = dataset.map(map_label)

    # Verify mapping
    labels = labeled_ds['label']
    unique, counts = np.unique(labels, return_counts=True)
    print("\nLabel distribution after mapping:")
    for label_id, count in zip(unique, counts):
        print(f"  Class {label_id} ({id2label[label_id]}): {count} samples")

    return labeled_ds, label2id, id2label

def create_stratified_splits(dataset, test_size=0.15, val_size=0.15, seed=42):
    """Create train/val/test splits with stratification"""
    print(f"\nCreating splits (test={test_size}, val={val_size})...")

    # Get indices and labels
    indices = list(range(len(dataset)))
    labels = dataset['label']

    # First split: train vs (val+test)
    train_idx, temp_idx = train_test_split(
        indices,
        test_size=(val_size + test_size),
        stratify=labels,
        random_state=seed,
        shuffle=True
    )

    # Second split: val vs test
    temp_labels = [labels[i] for i in temp_idx]
    val_idx, test_idx = train_test_split(
        temp_idx,
        test_size=test_size/(val_size + test_size),
        stratify=temp_labels,
        random_state=seed,
        shuffle=True
    )

    # Create DatasetDict
    splits = DatasetDict({
        'train': dataset.select(train_idx),
        'val': dataset.select(val_idx),
        'test': dataset.select(test_idx)
    })

    # Print statistics
    print("\nSplit Statistics:")
    for split_name in ['train', 'val', 'test']:
        split = splits[split_name]
        split_labels = split['label']
        n_samples = len(split)

        unique, counts = np.unique(split_labels, return_counts=True)
        print(f"\n{split_name.upper()} ({n_samples} samples):")
        for label_id, count in zip(unique, counts):
            print(f"  Class {label_id}: {count} samples ({count/n_samples*100:.1f}%)")

    return splits

