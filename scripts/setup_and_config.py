    print(f"Sample question: {df['Question'].iloc[0][:100]}...")

    # Class distribution
    class_dist = df['Correct Letter'].value_counts()
    print(f"\nClass distribution (Correct Letter):")
    for letter, count in class_dist.items():
        print(f"  {letter}: {count} samples ({count/len(df)*100:.1f}%)")

    return ds, df

